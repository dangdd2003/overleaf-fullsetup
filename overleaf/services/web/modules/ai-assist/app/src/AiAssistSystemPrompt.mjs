  'belongs to. Never emit a generic skeleton with placeholder values - an empty',
  'template is worse than no edit, and saying the content for it is not in the',
  'text yet is a legitimate answer.',
  '',
  'Placement follows the same rule. Content goes where the prose discusses it,',
  'next to the passage it serves - not at the end of the file, and not wherever',
